/**
 * ฟังก์ชันค้นหากฎคีย์เวิร์ด (Partial Matching บนข้อความยาวไม่เกิน 500 ตัวอักษร)
 */
export function matchAutoResponseRule(userText: string): AutoResponseRule | null {
  if (!userText || userText.length > 500) return null;
  const clean = userText.trim().toLowerCase();

  // อย่าดักข้อความที่เป็นคำสั่งสั่งซื้อชัดเจน เช่น สั่ง หรือมีจำนวนเลข เช่น "2 โล"
  const isOrderStatement = /(สั่ง|เอา|ขอ|ถุง|กก\.|กิโล|[0-9]+)/.test(clean);

  for (const rule of AUTO_RESPONSE_RULES) {
    // ถ้าเป็นข้อความสั่งซื้อ ห้ามดักกฎไก่/หมู ให้ผ่านไปเข้า Gemini AI คำนวณบิล
    if (isOrderStatement && (rule.ruleId === "RULE_CHICKEN" || rule.ruleId === "RULE_PORK")) {
      continue;
    }

    const matched = rule.keywords.some((kw) => clean.includes(kw.toLowerCase()));
    if (matched) {
      return rule;
    }
  }

  return null;
}
